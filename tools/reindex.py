#!/usr/bin/env python3
"""reindex - the skills-library engine. Single source of truth = each skill file's
frontmatter. Builds (all git-ignored, so parallel PRs never conflict on them):
  - skills.index.jsonl   (one line per skill; grep this to find skills)
  - <category>/INDEX.md  (lists fields in that category + counts)
  - <category>/<field>/INDEX.md (lists products + their skills)
Runs automatically after pull/checkout once hooks are on (git config core.hooksPath .githooks).
Needs PyYAML (pip install -r requirements.txt). Run: python tools/reindex.py
"""
import os, sys, json, re
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
MANIFEST = ROOT / "skills.index.jsonl"
README = ROOT / "README.md"
STATS_START = "<!-- STATS:START (generated by tools/reindex.py — do not edit by hand) -->"
STATS_END = "<!-- STATS:END -->"
STATUS_RE = re.compile(r"(<!-- STATUS:START -->).*?(<!-- STATUS:END -->)", re.S)
STATS_RE = re.compile(re.escape(STATS_START) + r'.*?' + re.escape(STATS_END), re.S)

FM_RE = re.compile(r'^---\s*\n(.*?)\n---\s*\n', re.S)

def parse_frontmatter(text):
    m = FM_RE.match(text)
    if not m:
        return None
    try:
        fm = yaml.safe_load(m.group(1))
    except yaml.YAMLError:
        return None
    if not isinstance(fm, dict):
        return None
    # YAML turns `on`/`2024` into bools/ints; every field here is text (or a list of text)
    return {k: [str(x) for x in v] if isinstance(v, list) else ('' if v is None else str(v))
            for k, v in fm.items()}

def load_skills():
    skills = []
    for p in sorted(SKILLS.rglob("*.md")):
        if p.name.upper() == "INDEX.MD":
            continue
        fm = parse_frontmatter(p.read_text(encoding="utf-8"))
        if not fm or 'name' not in fm:
            continue
        rel = p.relative_to(SKILLS).as_posix()
        parts = rel.split('/')
        cat = fm.get('category', parts[0] if len(parts) > 0 else '')
        field = fm.get('field', parts[1] if len(parts) > 1 else '')
        prod = fm.get('product', parts[2] if len(parts) > 2 else '')
        name = fm.get('name', p.stem)
        rec = {
            "id": fm.get('id') or f"{cat}.{field}.{prod}.{name}",
            "name": name, "category": cat, "field": field, "product": prod,
            "tags": fm.get('tags', []), "level": fm.get('level', ''),
            "status": fm.get('status', ''), "desc": fm.get('description', ''),
            "licence": fm.get('licence', ''), "aliases": fm.get('aliases', []),
            "version": fm.get('version', ''), "updated": fm.get('updated', ''),
            "path": "skills/" + rel,
        }
        skills.append(rec)
    return skills

def write_if_changed(path, content, changes):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == content:
        return
    changes.append(str(path.relative_to(ROOT)))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")

def gen_manifest(skills, changes):
    lines = [json.dumps(s, ensure_ascii=False, sort_keys=True) for s in skills]
    write_if_changed(MANIFEST, "\n".join(lines) + ("\n" if lines else ""), changes)

def gen_field_index(cat, field, items, changes):
    by_prod = {}
    for s in items:
        by_prod.setdefault(s['product'], []).append(s)
    out = [f"# {cat} / {field}", "",
           f"_{len(items)} skills. Generated by tools/reindex.py — do not edit._", ""]
    for prod in sorted(by_prod):
        out.append(f"## {prod}")
        for s in sorted(by_prod[prod], key=lambda x: x['name']):
            tags = ", ".join(s['tags'][:6])
            out.append(f"- **{s['name']}** [{s['status']}] — {s['desc']}  ·  `{s['path']}`  ·  _{tags}_")
        out.append("")
    write_if_changed(SKILLS / cat / field / "INDEX.md", "\n".join(out), changes)

def gen_category_index(cat, items, changes):
    by_field = {}
    for s in items:
        by_field.setdefault(s['field'], []).append(s)
    out = [f"# {cat}", "",
           f"_{len(items)} skills across {len(by_field)} fields. Generated — do not edit._", "",
           "| field | skills | products |", "|---|---|---|"]
    for field in sorted(by_field):
        prods = sorted({s['product'] for s in by_field[field]})
        out.append(f"| [{field}]({field}/INDEX.md) | {len(by_field[field])} | {', '.join(prods)} |")
    out.append("")
    write_if_changed(SKILLS / cat / "INDEX.md", "\n".join(out), changes)
    for field, fitems in by_field.items():
        gen_field_index(cat, field, fitems, changes)

def gen_readme_stats(by_cat, changes):
    if not README.exists() or not STATS_RE.search(README.read_text(encoding="utf-8")):
        return
    taxonomy = yaml.safe_load((ROOT / "taxonomy" / "categories.yaml").read_text(encoding="utf-8"))
    n_total_cats = len(taxonomy["categories"])
    rows = []
    for cat, items in sorted(by_cat.items(), key=lambda kv: -len(kv[1])):
        n_fields = len({s['field'] for s in items})
        rows.append(f"| {cat} | {n_fields} | {len(items)} |")
    total_skills = sum(len(items) for items in by_cat.values())
    total_fields = sum(len({s['field'] for s in items}) for items in by_cat.values())
    table = "\n".join([
        f"_{len(by_cat)}/{n_total_cats} categories started, {total_skills} skills total._",
        "",
        "| category | fields with skills | skills |",
        "|---|---|---|",
        *rows,
        f"| **total** | **{total_fields}** | **{total_skills}** |",
    ])
    text = README.read_text(encoding="utf-8")
    from collections import Counter
    c = Counter(s.get("status") for items in by_cat.values() for s in items)
    line = " · ".join(f"{c[k]:,} {k}" for k in ("verified", "docs-checked", "gated", "draft")) + f" of {total_skills:,} skills"
    text = STATUS_RE.sub(lambda m: f"{m.group(1)}{line}{m.group(2)}", text)
    block = f"{STATS_START}\n{table}\n{STATS_END}"
    new_text = STATS_RE.sub(lambda m: block, text)
    if new_text != text:
        changes.append(str(README.relative_to(ROOT)))
        README.write_text(new_text, encoding="utf-8", newline="\n")

def main():
    skills = load_skills()
    changes = []
    gen_manifest(skills, changes)
    by_cat = {}
    for s in skills:
        by_cat.setdefault(s['category'], []).append(s)
    for cat, items in by_cat.items():
        gen_category_index(cat, items, changes)
    gen_readme_stats(by_cat, changes)
    print(f"skills: {len(skills)}  categories: {len(by_cat)}  " + (f"updated {len(changes)} files" if changes else "up to date"))

if __name__ == "__main__":
    main()
